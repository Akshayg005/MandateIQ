"""The five stress regimes -- B13.

PRE-REGISTERED. Each regime below carries a `hypothesis` written BEFORE any
result under it was seen (see the block's DECISIONS.md entry for the commit
that fixes this file). A regime is a deviation from the frozen generative
parameters, expressed as an OVERLAY on eval/frozen/sim_config.yaml -- never
as an edit to it. `eval/frozen/` is immutable after the Day-1 freeze
(CLAUDE.md invariant 4); a regime that needed to change the simulator's code
would be a regime this harness is not entitled to run.

That constraint is real and it shapes what a regime can say. The frozen
simulator reads a fixed set of knobs -- cause_mix, the per-cause hazard base
rates and logit adjustments, the amount and category mixes, and the
per-arm parameters. A regime is a coherent story told in those knobs and nothing
else. Where a story could only be told by new simulator code (a true
time-varying outage window, for instance), the regime approximates it with
the knobs that exist and SAYS SO in `approximation`, rather than quietly
implying a fidelity it does not have.

**Do not edit this file after a result has been seen.** A policy that wins
every regime is evidence the regimes were tuned, not evidence the policy is
good; the whole value of pre-registration is that it is checkable afterwards
by `git log`.
"""
from __future__ import annotations

import copy
from dataclasses import dataclass, field
from typing import Any, Mapping

__all__ = [
    "RegimeSpec",
    "REGIMES",
    "REGIME_ARMS",
    "arms_for",
    "apply_overlay",
    "config_for",
    "validate_config",
]


def _deep_merge(base: dict, overlay: Mapping[str, Any]) -> dict:
    """Recursive dict merge. A scalar in the overlay replaces the base value;
    a mapping recurses. Deliberately refuses to introduce a key the base does
    not already have -- a typo'd knob name would otherwise silently do
    nothing, which is the failure mode that makes a regime a no-op and its
    result meaningless."""
    out = copy.deepcopy(base)
    for k, v in overlay.items():
        if k not in out:
            raise KeyError(
                f"regime overlay sets unknown config key {k!r} -- the frozen "
                f"sim_config.yaml has no such knob, so this override would be "
                f"silently ignored. Known keys here: {sorted(out)}"
            )
        if isinstance(v, Mapping) and isinstance(out[k], dict):
            out[k] = _deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


@dataclass(frozen=True)
class RegimeSpec:
    """One pre-registered deviation from the frozen generative parameters.

    name          -- stable identifier, used as the key in every artifact.
    story         -- the real-world situation being modelled, in one sentence.
    hypothesis    -- what we expect to happen to the three bars, written
                     BEFORE the run. This is the falsifiable part.
    approximation -- where the available knobs cannot express the story
                     faithfully, exactly how it falls short. Empty string only
                     if the overlay really does express the story.
    overlay       -- deep-merged onto the frozen config.
    """

    name: str
    story: str
    hypothesis: str
    approximation: str
    overlay: dict[str, Any] = field(default_factory=dict)


