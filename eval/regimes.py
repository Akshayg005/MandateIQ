# stacking_spike only says anything under the arm that models households at
# all. Running it under nominal/misspecified would produce a column identical
# to baseline's and invite reading it as a result.
REGIME_ARMS: dict[str, tuple[str, ...]] = {
    "stacking_spike": ("coupled",),
}


def arms_for(regime: str, all_arms: tuple[str, ...]) -> tuple[str, ...]:
    return REGIME_ARMS.get(regime, all_arms)


def validate_config(cfg: Mapping[str, Any]) -> None:
    """A regime overlay must still describe a valid generative process. The
    per-cause base rates are probabilities of disjoint terminal events at one
    attempt; if they sum to >= 1 there is no probability left for
    STILL_PENDING and the simulator would be describing something other than
    what the protocol says it describes."""
    mix = cfg["cause_mix"]
    total = sum(mix.values())
    if abs(total - 1.0) > 1e-9:
        raise ValueError(f"cause_mix must sum to 1.0, got {total!r}")
    for cause, h in cfg["hazards"].items():
        base = h["base_recovery"] + h["base_dead"] + h["base_optout"]
        if not (0.0 < base < 1.0):
            raise ValueError(
                f"hazards.{cause}: base_recovery+base_dead+base_optout = "
                f"{base!r}, must be strictly between 0 and 1 to leave "
                f"probability mass for STILL_PENDING"
            )
    lo, hi = cfg["amount_paise"]["below_afa_range"]
    if lo >= hi:
        raise ValueError(f"below_afa_range is not increasing: {[lo, hi]}")
    frac = cfg["amount_paise"]["below_afa_frac"]
    if not (0.0 <= frac <= 1.0):
        raise ValueError(f"below_afa_frac must be in [0, 1], got {frac!r}")


def apply_overlay(base: Mapping[str, Any], overlay: Mapping[str, Any]) -> dict:
    merged = _deep_merge(dict(base), overlay)
    validate_config(merged)
    return merged


def config_for(regime: str, base: Mapping[str, Any]) -> dict:
    """The frozen config with `regime`'s overlay applied. `base` is passed in
    rather than loaded here so a caller cannot accidentally mutate the
    module-level frozen config between regimes."""
    if regime not in REGIMES:
        raise KeyError(f"unknown regime {regime!r}; known: {sorted(REGIMES)}")
    return apply_overlay(base, REGIMES[regime].overlay)
